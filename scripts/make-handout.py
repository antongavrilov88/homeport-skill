#!/usr/bin/env python3
"""Памятка для человека: одна страница, всё нужное, без жаргона.

    python3 make-handout.py --params params.json --out pamyatka.md

Отдавать файлом (SendUserFile). НЕ публиковать: внутри код от панели
и пароль от уведомлений.
"""
import argparse, json


T = """# Твой VPN — памятка

Сохрани этот файл. Здесь всё, что нужно знать, чтобы пользоваться и не звать
на помощь по мелочам.

---

## Как добавить устройство

1. Подключись к VPN с любого устройства, которое уже настроено.
2. Открой в браузере **{dash}**
3. Если спросит код — введи **{token}**
4. Нажми **+ New client**, напиши имя (например «Телефон мамы»), нажми
   **Create and show QR**.
5. На новом устройстве открой приложение **WireGuard** и отсканируй QR-код.

Приложение WireGuard бесплатное, есть везде: App Store, Google Play, а для
компьютера — на сайте wireguard.com.

**Если устройство в сети, где VPN не подключается** (отель, метро, рабочий
вайфай) — при создании клиента выбери порт **443** вместо обычного. Такое
соединение проходит почти везде.

---

## Панель: что там показано

- кто сейчас онлайн и сколько трафика потратил;
- график расхода;
- список устройств; лишнее можно удалить крестиком.

Панель открывается **только когда ты подключён к VPN**. Снаружи её нет — так
и задумано, чтобы никто посторонний туда не попал.

**Что НЕ собирается и нигде не хранится:** какие сайты открывают, что ищут,
что смотрят. Только счётчик мегабайт по каждому устройству. Это не «мы обещаем»,
а как оно устроено: логи выключены.

---

## Уведомления на телефон
{notify}

---

## Сколько это стоит

{money}

**Трафика хватает примерно на {capacity}.** Если начнёт не хватать — не надо
ничего переделывать, достаточно перейти на сервер вдвое дороже.

---

## Если перестало работать

Сначала подожди 2–3 минуты. Внутри всё устроено так, что при поломке
{failover}

Что можно проверить самому:

1. **Интернет вообще есть?** Выключи VPN на телефоне и открой любой сайт.
   Не открывается — дело не в VPN.
2. **Открой в браузере {site}** — это обычная страница, она должна открыться
   с любого устройства, даже без VPN. Открылась — сервер жив.
3. Не помогло — напиши тому, кто это настраивал, и покажи эту памятку.
   Всё, что нужно для разбора, в ней есть.

---

## Раз в год

У домена **{domain}** есть срок оплаты. Не продлишь — перестанет работать всё.
Поставь напоминание в календаре за месяц.

---

## Технические детали (не нужны, пока всё работает)

Пусть лежат здесь — понадобятся тому, кто будет чинить.

| | |
|---|---|
| Домен | `{domain}` |
| Адрес сервера{exit_label} | `{exit_ip}` |{relay_row}
| Панель | `{dash}`, код `{token}` |
| Схема | {scheme} |

Ключи и пароли — в отдельном файле `params.json`. **Его нельзя терять и нельзя
никому пересылать.** Положи в облако или менеджер паролей.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", required=True)
    ap.add_argument("--out", default="pamyatka.md")
    ap.add_argument("--price-exit", required=True,
                    help="the exit's monthly price quoted at setup (the host's listed price); no default: hosts change prices")
    ap.add_argument("--price-relay", default="")
    a = ap.parse_args()
    p = json.load(open(a.params, encoding="utf-8"))
    single = p.get("mode") == "single"
    gw = p.get("wg_subnet", "10.67.0") + ".1"
    dash = f'http://{gw}:{p.get("dashboard_port", 8088)}'

    if p.get("ntfy_alert_token") or p.get("push_domain"):
        notify = f"""
Поставь приложение **ntfy** (App Store / Google Play). В нём:

1. Нажми **+** → **Subscribe to topic**
2. Включи **Use another server** и впиши: `https://{p["push_domain"]}`
3. Имя темы: `{p["ntfy_topic"]}`
4. Логин `{p["ntfy_user"]}`, пароль `{p["ntfy_pass"]}`

Приходить будет только по делу: если что-то сломалось и если починилось само.
Раз в месяц ночью система сама себя проверяет — от этой проверки тоже придёт
короткий отчёт, это норма.
"""
    else:
        notify = "\nУведомления не настраивались.\n"

    money = f"- сервер за границей — **{a.price_exit} в месяц**\n- домен — **примерно 1000 ₽ в год**"
    if not single:
        money += f"\n- сервер в домашней стране — **{a.price_relay or '300–600 ₽ в месяц'}**"

    if single:
        failover = ("система сама перезапускает то, что зависло, и пишет тебе. "
                    "Часто за эти пару минут всё поднимается само.")
        scheme = "одна машина за границей"
        relay_row = ""
        exit_label = ""
        capacity = "10–15 устройств при обычном пользовании или 4–5 человек, смотрящих видео"
    else:
        failover = ("людей автоматически переводят на запасной путь примерно за минуту — "
                    "местные сайты остаются доступны, заграничные на это время — нет. "
                    "Когда основной канал чинится, всех возвращают обратно, тоже само.")
        scheme = "две машины: перевалочная в домашней стране + выход за границей"
        relay_row = f'\n| Перевалочный сервер | `{p.get("relay_ip", "—")}` |'
        exit_label = " за границей"
        capacity = "10–15 устройств при обычном пользовании или 4–5 человек, смотрящих видео"

    text = T.format(dash=dash, token=p.get("dashboard_token", ""), notify=notify.strip(),
                    money=money, capacity=capacity, failover=failover,
                    site=f'https://{p["domain"]}', domain=p["domain"],
                    exit_ip=p.get("exit_ip", "—"), exit_label=exit_label,
                    relay_row=relay_row, scheme=scheme)
    open(a.out, "w", encoding="utf-8").write(text)
    print(a.out)


if __name__ == "__main__":
    main()
